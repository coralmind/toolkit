"""Burr graph definitions for L3 conversation-loop simulations.

This module builds the directed graph that orchestrates multi-turn
conversations between a simulated person and the system under test (SUT).
The graph is constructed via Burr's ``GraphBuilder`` and returned alongside
an initial state dict, ready to be wrapped in an ``ApplicationBuilder`` by
the runner (``corallab.simulation.setup.simulation_runner``).

One public graph builder is provided:

- ``build_l3_sim_graph`` — persona-prompted simulation.  The person's
  messages are generated by an LLM conditioned on a persona description
  but without explicit psychological state tracking.

A second public function, ``build_sim_subgraph``, wraps the appropriate
graph as a Burr ``RunnableGraph`` for use inside ``MapStates`` fan-outs
during sim-only batch execution (the ``sim`` CLI command).

L3 graph topology::

    send_opening → call_sut → check_exit
    check_exit ──(exit)──→ assemble
    check_exit ──(cont)──→ generate_persona → call_sut  (loop)

Private helpers factor out component construction (person response generator)
and initial-state assembly.
"""

from __future__ import annotations

import logging
from typing import Any

from burr.core import default, when
from burr.core.graph import Graph, GraphBuilder
from burr.core.parallelism import RunnableGraph

from corallab.schemas.eval.run_manifest import (
    DEFAULT_PERSON_RESPONSE_MODEL_TEMPERATURE,
)
from corallab.simulation.actions.run_simulation import RunSimulation
from corallab.simulation.actions.system_under_test import SystemUnderTest

logger = logging.getLogger(__name__)


def build_sim_subgraph(evaluation_level: int) -> RunnableGraph:
    """Return a ``RunnableGraph`` for sim-only batch execution at the given level.

    Used by ``ParallelSim`` (``MapStates`` fan-out) to execute one test case.
    The returned graph is level-dependent:

    - **L1/L2**: A single ``SystemUnderTest`` node that calls the model under
      test with the scripted prompt and writes the ``transcript`` record.
    - **L3**: A single ``RunSimulation`` node (which internally builds and
      runs the full conversation-loop sub-application).

    Args:
        evaluation_level: The evaluation depth (1–3).

    Returns:
        A ``RunnableGraph`` with entrypoint and halt_after configured.
    """
    if evaluation_level >= 3:
        graph = (
            GraphBuilder()
            .with_actions(
                simulate=RunSimulation(),
            )
            .build()
        )
        return RunnableGraph(
            graph=graph,
            entrypoint="simulate",
            halt_after=["simulate"],
        )

    graph = GraphBuilder().with_actions(system_under_test=SystemUnderTest()).build()
    return RunnableGraph(
        graph=graph,
        entrypoint="system_under_test",
        halt_after=["system_under_test"],
    )


# ------------------------------------------------------------------
# Shared component factories for conversation-loop graphs
# ------------------------------------------------------------------


def _create_person_response_generator(
    sim_client: Any,
    persona: Any,
    scenario_content: dict,
    run_config: Any,
) -> Any:
    """Construct a ``PersonResponseGenerator`` for one L3 conversation.

    Model id, temperature, and retry settings come from
    ``run_config.simulation.person_response_model``.
    """
    from corallab.simulation.person_response_generator import PersonResponseGenerator

    model = run_config.simulation.person_response_model
    return PersonResponseGenerator(
        client=sim_client,
        persona=persona,
        scenario_content=scenario_content,
        model=model.model_id,
        temperature=model.temperature_or(DEFAULT_PERSON_RESPONSE_MODEL_TEMPERATURE),
        retry_max=run_config.retry_max,
        retry_backoff_ms=run_config.retry_backoff_ms,
        extra_params=model.completion_params(),
    )


def _make_initial_state(
    test_case_id: str,
    run_config: Any,
) -> dict[str, Any]:
    """Build the initial Burr state dict for the L3 conversation loop.

    This dict is passed to ``ApplicationBuilder.with_state()`` and seeds every
    state key that the conversation-loop actions read or write.
    """
    return {
        "test_case_id": test_case_id,
        "max_turns": run_config.simulation.max_turns,
        "conversation_history": [],
        "turn_number": 0,
        "round_count": 0,
        "should_exit": False,
        "exit_reason": "",
        "conversation_closing": False,
        "scenario_enacted": False,
        "sim_result": None,
    }


# ------------------------------------------------------------------
# L3 conversation-loop graph
# ------------------------------------------------------------------


def build_l3_sim_graph(
    persona: Any,
    scenario_content: dict,
    run_config: Any,
    sim_client: Any,
    sut_client: Any,
    test_case_id: str,
) -> tuple[Graph, dict[str, Any]]:
    """Build the L3 (persona-prompted) conversation-loop graph.

    The L3 loop is a simple generate-and-respond cycle: an opening message is
    sent to the SUT, and each SUT reply is checked for exit conditions before
    ``PersonResponseGenerator`` writes the next person message.  There is no
    state tracking, response classification, or behavioral directive generation.

    Args:
        persona: Persona specification (traits, identity, register).
        scenario_content: Scenario dict including opening message and system
            prompt for the SUT.
        run_config: ``RunConfig`` with model IDs, temperatures, retry settings,
            and conversation limits.
        sim_client: LLM client for simulation-side calls (person response generation).
        sut_client: LLM client for calling the system under test.
        test_case_id: Unique identifier for this test case (used in results).

    Returns:
        A ``(Graph, initial_state_dict)`` tuple ready for
        ``ApplicationBuilder.with_graph(...).with_state(...)``.
    """
    from corallab.simulation.actions.sim_loop.assemble_sim_result import (
        AssembleSimResult,
    )
    from corallab.simulation.actions.sim_loop.call_sut import CallSUT
    from corallab.simulation.actions.sim_loop.check_exit import CheckExit
    from corallab.simulation.actions.sim_loop.generate_persona_message import (
        GeneratePersonaMessage,
    )
    from corallab.simulation.actions.sim_loop.send_opening import SendOpening

    response_generator = _create_person_response_generator(
        sim_client, persona, scenario_content, run_config
    )

    graph = (
        GraphBuilder()
        .with_actions(
            send_opening=SendOpening(scenario_content),
            call_sut=CallSUT(sut_client, run_config, scenario_content),
            check_exit=CheckExit(),
            generate_persona=GeneratePersonaMessage(response_generator),
            assemble=AssembleSimResult(run_config, level=3),
        )
        .with_transitions(
            ("send_opening", "call_sut", default),
            ("call_sut", "check_exit", default),
            ("check_exit", "assemble", when(should_exit=True)),
            ("check_exit", "generate_persona", default),
            ("generate_persona", "assemble", when(should_exit=True)),
            ("generate_persona", "call_sut", default),
        )
        .build()
    )

    initial_state = _make_initial_state(test_case_id, run_config)
    return graph, initial_state

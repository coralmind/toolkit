"""Generate the viewer's TypeScript types from the ingest's page models.

The models are ``coralmind_viewer.export_models``; the output is
``viewer/src/lib/generated-types.ts``, which the Next app imports for every generated file.

Usage::

    pixi run gen-viewer-types
    pixi run check-viewer-types

``--check`` exits non-zero when the committed file differs from what the models produce.
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from pathlib import Path
from typing import Any

from corallab.paths import repo_root
from coralmind_viewer.export_models import GENERATED_MODELS

logger = logging.getLogger(__name__)

HEADER = (
    "// Generated by scripts/gen_viewer_types.py from coralmind_viewer.export_models.\n"
    "// Do not edit: change the models and run `pixi run gen-viewer-types`."
)


def output_path() -> Path:
    return repo_root() / "viewer" / "src" / "lib" / "generated-types.ts"


def _ts(schema: dict[str, Any]) -> str:
    """The TypeScript type for one JSON Schema node."""
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(_ts(option) for option in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(_ts(item) for item in schema["prefixItems"]) + "]"
        item = _ts(schema.get("items", {}))
        return f"({item})[]" if " | " in item else f"{item}[]"
    if kind == "object":
        values = schema.get("additionalProperties", True)
        value = "unknown" if values is True or values == {} else _ts(values)
        return f"Record<string, {value}>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(str(kind), "unknown")


def _interface(name: str, schema: dict[str, Any]) -> str:
    lines = []
    if schema.get("description"):
        lines.append(f"/** {' '.join(str(schema['description']).split())} */")
    lines.append(f"export interface {name} {{")
    required = set(schema.get("required", []))
    for prop, value in schema.get("properties", {}).items():
        if value.get("description"):
            lines.append(f"  /** {' '.join(str(value['description']).split())} */")
        optional = "" if prop in required else "?"
        lines.append(f"  {prop}{optional}: {_ts(value)};")
    lines.append("}")
    return "\n".join(lines)


def render() -> str:
    """Every model the generated files use, each as an interface, in a stable order."""
    defs: dict[str, dict[str, Any]] = {}
    for model in GENERATED_MODELS:
        schema = model.model_json_schema(mode="serialization", ref_template="#/$defs/{model}")
        defs.update(schema.pop("$defs", {}))
        defs[model.__name__] = schema
    blocks = [HEADER, *(_interface(name, defs[name]) for name in sorted(defs))]
    return "\n\n".join(blocks) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when the file is stale")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    path = output_path()
    text = render()
    if args.check:
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        if current != text:
            logger.error("%s is stale; run `pixi run gen-viewer-types`.", path)
            return 1
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
